const STICKER_PATTERN = /^\[sticker:([\s\S]+)\]$/

/**
 * 构造贴纸消息文本
 * @param emoji 贴纸表情
 * @returns 贴纸消息文本
 */
export function buildStickerMessage(emoji) {
  return '[sticker:' + emoji + ']'
}

/**
 * 解析贴纸消息，仅整条消息完全匹配贴纸标记时生效
 * @param message 消息文本
 * @returns 贴纸表情，非贴纸消息返回 null
 */
export function parseSticker(message) {
  if (!message) {
    return null
  }
  const match = message.match(STICKER_PATTERN)
  return match ? match[1] : null
}
