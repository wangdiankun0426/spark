public enum DeleteFlagEnum {
    NORMAL(1, "正常"),
    DELETED(-1, "已删除"),
    ;
    private Integer value;

    private String desc;

    DeleteFlagEnum(Integer value, String desc) {
        this.value = value;
        this.desc = desc;
    }

    public Integer getValue() {
        return value;
    }

    public void setValue(Integer value) {
        this.value = value;
    }

    public String getDesc() {
        return desc;
    }

    public void setDesc(String desc) {
        this.desc = desc;
    }
}
